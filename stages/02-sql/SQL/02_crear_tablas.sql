USE Practica_Ventas;
GO

CREATE TABLE dbo.DIM_CATEGORY (
    ID_CATEGORY INT NOT NULL PRIMARY KEY,
    CATEGORY NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE dbo.DIM_PRODUCT (
    MANUFACTURER NVARCHAR(80) NOT NULL,
    BRAND NVARCHAR(80) NOT NULL,
    ITEM VARCHAR(30) NOT NULL,
    ITEM_DESCRIPTION NVARCHAR(200) NOT NULL,
    CATEGORY INT NOT NULL,
    [FORMAT] NVARCHAR(40) NOT NULL,
    ATTR1 NVARCHAR(60) NULL,
    ATTR2 NVARCHAR(60) NOT NULL,
    ATTR3 NVARCHAR(60) NULL,
    CONSTRAINT FK_DIM_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY)
        REFERENCES dbo.DIM_CATEGORY(ID_CATEGORY)
);
GO

CREATE TABLE dbo.DIM_SEGMENT (
    CATEGORY INT NOT NULL,
    ATTR1 NVARCHAR(60) NOT NULL,
    ATTR2 NVARCHAR(60) NOT NULL,
    ATTR3 NVARCHAR(60) NULL,
    [FORMAT] NVARCHAR(40) NOT NULL,
    SEGMENT NVARCHAR(60) NOT NULL,
    CONSTRAINT FK_DIM_SEGMENT_CATEGORY FOREIGN KEY (CATEGORY)
        REFERENCES dbo.DIM_CATEGORY(ID_CATEGORY)
);
GO

CREATE TABLE dbo.DIM_CALENDAR (
    [WEEK] VARCHAR(5) NOT NULL PRIMARY KEY,
    [YEAR] INT NOT NULL,
    [MONTH] INT NOT NULL,
    WEEK_NUMBER INT NOT NULL,
    [DATE] DATE NOT NULL
);
GO

-- Comprobar las tablas creadas.
SELECT TABLE_NAME
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'dbo' AND TABLE_NAME LIKE 'DIM_%'
ORDER BY TABLE_NAME;
GO

